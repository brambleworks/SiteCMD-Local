struct NativeConfirmationStep {
    function: String,
    requires: String,
}

struct NativeConfirmationContract {
    command: String,
    source: String,
    steps: Vec<NativeConfirmationStep>,
}

fn native_confirmed_manifest_entries() -> Vec<NativeConfirmationContract> {
    command_security_manifest()
        .get("nativeConfirmedCommands")
        .and_then(|value| value.as_array())
        .expect("nativeConfirmedCommands array")
        .iter()
        .map(|entry| {
            let command = entry
                .get("command")
                .and_then(|value| value.as_str())
                .expect("nativeConfirmedCommands command")
                .to_string();
            let source = entry
                .get("source")
                .and_then(|value| value.as_str())
                .expect("nativeConfirmedCommands source")
                .to_string();
            let steps = match entry.get("confirmationPath") {
                Some(value) => value
                    .as_array()
                    .filter(|path| !path.is_empty())
                    .expect("nativeConfirmedCommands confirmationPath must be a non-empty array")
                    .iter()
                    .map(|step| NativeConfirmationStep {
                        function: step
                            .get("function")
                            .and_then(|value| value.as_str())
                            .expect("nativeConfirmedCommands confirmationPath function")
                            .to_string(),
                        requires: step
                            .get("requires")
                            .and_then(|value| value.as_str())
                            .expect("nativeConfirmedCommands confirmationPath requires")
                            .to_string(),
                    })
                    .collect(),
                None => {
                    let function = entry
                        .get("confirmationFunction")
                        .and_then(|value| value.as_str())
                        .map(str::to_string)
                        .unwrap_or_else(|| command.clone());
                    let requires = entry
                        .get("requires")
                        .and_then(|value| value.as_str())
                        .expect("nativeConfirmedCommands requires")
                        .to_string();
                    vec![NativeConfirmationStep { function, requires }]
                }
            };
            NativeConfirmationContract {
                command,
                source,
                steps,
            }
        })
        .collect()
}

fn rust_source_files(dir: &Path, files: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };

    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            rust_source_files(&path, files);
        } else if path.extension().is_some_and(|extension| extension == "rs") {
            files.push(path);
        }
    }
}

/// True for a `cfg` predicate that holds only under `cargo test`: the bare
/// `test`, or an `all(...)` whose top-level list carries a bare `test`.
/// `any(test, ...)` and `not(test)` are deliberately excluded because both
/// can hold in a production build, so a module carrying them is production
/// code the source-scanning guardrails must keep seeing.
fn cfg_is_test_only(predicate: &str) -> bool {
    let trimmed = predicate.trim();
    if trimmed == "test" {
        return true;
    }
    let Some(list) = trimmed
        .strip_prefix("all(")
        .and_then(|rest| rest.strip_suffix(')'))
    else {
        return false;
    };
    let mut depth = 0usize;
    list.split(|ch| {
        match ch {
            '(' => depth += 1,
            ')' => depth = depth.saturating_sub(1),
            _ => {}
        }
        ch == ',' && depth == 0
    })
    .any(|item| item.trim() == "test")
}

/// Byte offset just past the `}` closing a block whose opening `{` the caller
/// already consumed, or `None` when the block never closes. Braces inside
/// string, raw-string, and character literals and inside `//` and `/* */`
/// comments do not count, so a `{` in a test fixture cannot swallow the file.
fn end_of_block(source: &str, body_start: usize) -> Option<usize> {
    let bytes = source.as_bytes();
    let mut index = body_start;
    let mut depth = 1usize;
    while index < bytes.len() {
        match bytes[index] {
            b'{' => {
                depth += 1;
                index += 1;
            }
            b'}' => {
                depth -= 1;
                index += 1;
                if depth == 0 {
                    return Some(index);
                }
            }
            b'/' if bytes.get(index + 1) == Some(&b'/') => {
                index = match source[index..].find('\n') {
                    Some(offset) => index + offset + 1,
                    None => bytes.len(),
                };
            }
            b'/' if bytes.get(index + 1) == Some(&b'*') => {
                index = end_of_block_comment(source, index + 2);
            }
            b'"' => index = end_of_string_literal(source, index + 1),
            b'r' | b'b' => match raw_string_hashes(source, index) {
                Some((quote, hashes)) => index = end_of_raw_string(source, quote + 1, hashes),
                None => index += 1,
            },
            b'\'' => index = end_of_char_literal(source, index),
            _ => index += 1,
        }
    }
    None
}

/// Offset just past the terminating `*/`, honouring Rust's nested block
/// comments. `index` points just past the opening `/*`.
fn end_of_block_comment(source: &str, mut index: usize) -> usize {
    let bytes = source.as_bytes();
    let mut depth = 1usize;
    while index < bytes.len() {
        if bytes[index] == b'/' && bytes.get(index + 1) == Some(&b'*') {
            depth += 1;
            index += 2;
        } else if bytes[index] == b'*' && bytes.get(index + 1) == Some(&b'/') {
            depth -= 1;
            index += 2;
            if depth == 0 {
                return index;
            }
        } else {
            index += 1;
        }
    }
    bytes.len()
}

/// Offset just past the closing `"`. `index` points just past the opening
/// quote; `\"` and `\\` do not terminate the literal.
fn end_of_string_literal(source: &str, mut index: usize) -> usize {
    let bytes = source.as_bytes();
    while index < bytes.len() {
        match bytes[index] {
            b'\\' => index += 2,
            b'"' => return index + 1,
            _ => index += 1,
        }
    }
    bytes.len()
}

/// `(offset of the opening quote, hash count)` when `index` starts a raw
/// string (`r"`, `r#"`, `br"`, `br##"`, ...) rather than an identifier that
/// merely begins with `r` or `b`.
fn raw_string_hashes(source: &str, index: usize) -> Option<(usize, usize)> {
    let bytes = source.as_bytes();
    let previous = index.checked_sub(1).map(|before| bytes[before]);
    if previous.is_some_and(|byte| byte.is_ascii_alphanumeric() || byte == b'_') {
        return None;
    }
    let mut cursor = index;
    if bytes[cursor] == b'b' {
        cursor += 1;
    }
    if bytes.get(cursor) != Some(&b'r') {
        return None;
    }
    cursor += 1;
    let hashes_start = cursor;
    while bytes.get(cursor) == Some(&b'#') {
        cursor += 1;
    }
    if bytes.get(cursor) != Some(&b'"') {
        return None;
    }
    Some((cursor, cursor - hashes_start))
}

/// Offset just past a raw string's terminating `"` plus its `#` run.
/// `index` points just past the opening quote.
fn end_of_raw_string(source: &str, mut index: usize, hashes: usize) -> usize {
    let bytes = source.as_bytes();
    let closing = format!("\"{}", "#".repeat(hashes));
    match source[index..].find(&closing) {
        Some(offset) => {
            index += offset + closing.len();
            index
        }
        None => bytes.len(),
    }
}

/// Offset just past a character literal's closing `'`, or just past the
/// opening `'` when this is a lifetime rather than a literal.
fn end_of_char_literal(source: &str, index: usize) -> usize {
    let bytes = source.as_bytes();
    if bytes.get(index + 1) == Some(&b'\\') {
        let mut cursor = index + 2;
        if bytes.get(cursor) == Some(&b'u') {
            while cursor < bytes.len() && bytes[cursor] != b'}' {
                cursor += 1;
            }
            cursor += 1;
        } else {
            cursor += 1;
        }
        if bytes.get(cursor) == Some(&b'\'') {
            return cursor + 1;
        }
        return index + 1;
    }
    if let Some(character) = source[index + 1..].chars().next() {
        let after = index + 1 + character.len_utf8();
        if bytes.get(after) == Some(&b'\'') {
            return after + 1;
        }
    }
    index + 1
}

/// Source with every inline test module excised. A `#[cfg(test)]` attribute
/// (or a compound test-only form such as `#[cfg(all(test, feature =
/// "desktop"))]`) followed, after optional whitespace and other attribute
/// lines, by `mod <ident> {` opens an inline test module; its body is matched
/// brace for brace, replaced by the newlines it spanned, and the scan
/// continues after its closing brace. Production code on *both* sides of a
/// test module therefore stays visible to the source-scanning guardrails, and
/// every surviving line keeps its original line number so a guardrail can
/// report `file:line` accurately. A `#[cfg(test)] mod tests;` declaration, or
/// a `#[cfg(test)]` on a `use`, field, or function, does not match.
fn production_half(source: &str) -> String {
    let inline_test_module = regex::Regex::new(
        r"#\[cfg\(([^\]]*)\)\](?:\s*#\[[^\]]*\])*\s*mod\s+[A-Za-z_][A-Za-z0-9_]*\s*\{",
    )
    .expect("inline test module pattern");

    let mut kept = String::with_capacity(source.len());
    let mut cursor = 0usize;
    loop {
        let Some(captures) = inline_test_module.captures(&source[cursor..]) else {
            kept.push_str(&source[cursor..]);
            return kept;
        };
        let matched = captures.get(0).expect("whole match");
        let start = cursor + matched.start();
        let body = cursor + matched.end();
        let predicate = captures.get(1).map_or("", |group| group.as_str());
        if !cfg_is_test_only(predicate) {
            kept.push_str(&source[cursor..body]);
            cursor = body;
            continue;
        }
        kept.push_str(&source[cursor..start]);
        // An unbalanced module body cannot be excised safely; drop the rest
        // rather than let test code count as production.
        let Some(end) = end_of_block(source, body) else {
            return kept;
        };
        for _ in 0..source[start..end].matches('\n').count() {
            kept.push('\n');
        }
        cursor = end;
    }
}

fn tracing_instrument_attributes(source: &str) -> Vec<(usize, &str)> {
    let marker = concat!("#[", "tracing::instrument");
    let mut attributes = Vec::new();
    let mut index = 0;

    while let Some(relative_start) = source[index..].find(marker) {
        let start = index + relative_start;
        let Some(relative_end) = source[start..].find(']') else {
            break;
        };
        let end = start + relative_end + 1;
        let line = source[..start].lines().count() + 1;
        attributes.push((line, &source[start..end]));
        index = end;
    }

    attributes
}

fn tracing_field_assignment_is_unsafe(attribute: &str) -> bool {
    let normalized: String = attribute
        .to_ascii_lowercase()
        .chars()
        .filter(|ch| !ch.is_whitespace())
        .collect();
    if !normalized.contains("fields(") {
        return false;
    }

    let unsafe_fields = [
        "raw",
        "password",
        "passwd",
        "secret",
        "token",
        "api_key",
        "apikey",
        "credential",
        "authorization",
        "database_url",
        "db_url",
        "path",
        "src_path",
        "dest_path",
        "source_path",
        "project_path",
        "project_root",
        "env_file_path",
        "working_dir",
    ];

    unsafe_fields.iter().any(|field| {
        normalized.contains(&format!("fields({}=", field))
            || normalized.contains(&format!(",{}=", field))
    })
}

// Extract functions carrying bare or conditional Tauri command attributes.
fn tauri_command_annotated_fn_names(source: &str) -> Vec<String> {
    let attribute_marker = concat!("tauri", "::command");
    let lines: Vec<&str> = source.lines().collect();
    let mut names = Vec::new();
    for (index, line) in lines.iter().enumerate() {
        let trimmed = line.trim_start();
        if !trimmed.starts_with("#[") || !trimmed.contains(attribute_marker) {
            continue;
        }
        // Allow a few intervening attributes (e.g. tracing::instrument)
        // between the annotation and the fn signature.
        for following in lines.iter().skip(index + 1).take(8) {
            if let Some(name) = fn_name_in_signature_line(following) {
                names.push(name);
                break;
            }
        }
    }
    names
}

fn fn_name_in_signature_line(line: &str) -> Option<String> {
    let mut tokens = line.split_whitespace();
    tokens.find(|token| *token == "fn")?;
    let name: String = tokens
        .next()?
        .chars()
        .take_while(|ch| ch.is_ascii_alphanumeric() || *ch == '_')
        .collect();
    (!name.is_empty()).then_some(name)
}

fn function_body_contains(source: &str, fn_name: &str, needle: &str) -> bool {
    let marker = format!("fn {}", fn_name);
    let mut search_start = 0;

    while let Some(relative_start) = source[search_start..].find(&marker) {
        let signature_start = search_start + relative_start;
        let tail_start = signature_start + marker.len();
        if source[tail_start..]
            .chars()
            .next()
            .is_some_and(|ch| ch == '_' || ch.is_ascii_alphanumeric())
        {
            search_start = tail_start;
            continue;
        }
        let Some(boundary_offset) = source[tail_start..].find([';', '{']) else {
            return false;
        };
        let boundary = tail_start + boundary_offset;
        if source.as_bytes()[boundary] == b';' {
            search_start = boundary + 1;
            continue;
        }

        let mut depth = 0usize;
        let mut body_closed = false;
        for (offset, ch) in source[boundary..].char_indices() {
            if ch == '{' {
                depth += 1;
            } else if ch == '}' {
                depth = depth.saturating_sub(1);
                if depth == 0 {
                    if source[boundary..boundary + offset].contains(needle) {
                        return true;
                    }
                    search_start = boundary + offset + 1;
                    body_closed = true;
                    break;
                }
            }
        }
        if !body_closed {
            return false;
        }
    }

    false
}

#[test]
fn function_body_match_skips_declarations_and_name_prefixes() {
    let source = r#"
        trait Ports { async fn confirm_replacement(&self); }
        fn confirm_replacement_preview() { confirm_sensitive_action(); }
        impl Ports for DesktopPorts {
            async fn confirm_replacement(&self) { confirm_sensitive_action(); }
        }
    "#;

    assert!(function_body_contains(
        source,
        "confirm_replacement",
        "confirm_sensitive_action("
    ));
    assert!(!function_body_contains(
        "async fn confirm_replacement() {",
        "confirm_replacement",
        "confirm_sensitive_action("
    ));
}

// Guard: the `APP_COMMANDS` list in `build.rs` must contain every
// `#[tauri::command]` handler registered in `invoke_handler!`. If they
// drift, the ACL manifest won't gate the new command - any webview can
// call it.
