fn app_commands_list_matches_invoke_handler() {
    let lib_cmds = invoke_handler_command_names();
    let build_cmds = app_manifest_command_names();

    let missing_in_build: Vec<_> = lib_cmds.difference(&build_cmds).collect();
    let missing_in_lib: Vec<_> = build_cmds.difference(&lib_cmds).collect();
    assert!(
        missing_in_build.is_empty() && missing_in_lib.is_empty(),
        "APP_COMMANDS and invoke_handler! drifted.\n  in lib.rs but not build.rs: {:?}\n  in build.rs but not lib.rs: {:?}",
        missing_in_build,
        missing_in_lib,
    );
}

