#[test]
fn frontend_invoke_literals_match_registered_commands() {
    let repo_root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("repo root");
    let src_dir = repo_root.join("src");
    let mut files = Vec::new();
    fn ts_source_files(dir: &Path, files: &mut Vec<PathBuf>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                ts_source_files(&path, files);
            } else if path
                .extension()
                .is_some_and(|extension| extension == "ts" || extension == "tsx")
            {
                files.push(path);
            }
        }
    }
    ts_source_files(&src_dir, &mut files);

    let registered = app_manifest_command_names();
    let invoke_regex =
        regex::Regex::new(r#"\binvoke(?:\s*<[\s\S]*?>)?\s*\(\s*([^,\n)]+)"#).expect("invoke regex");
    let literal_regex = regex::Regex::new(r#"^["']([a-z0-9_]+)["']$"#).expect("literal regex");
    let mut missing_commands = Vec::new();
    let mut dynamic_calls = Vec::new();

    for file in files {
        let relative = file
            .strip_prefix(repo_root)
            .unwrap_or(&file)
            .to_string_lossy()
            .replace('\\', "/");
        if relative.ends_with(".test.ts")
            || relative.ends_with(".test.tsx")
            || relative.ends_with(".spec.ts")
            || relative.ends_with(".spec.tsx")
            || relative.ends_with(".behavior.ts")
            || relative.ends_with(".behavior.tsx")
            || relative.ends_with(".render.ts")
            || relative.ends_with(".render.tsx")
            || relative == "src/lib/tauri-invoke.ts"
            || relative == "src/lib/privileged-command-bridge.ts"
            || relative.starts_with("src/lib/commands/")
        {
            continue;
        }

        let source = std::fs::read_to_string(&file).expect("read frontend source");
        for capture in invoke_regex.captures_iter(&source) {
            let Some(matched) = capture.get(0) else {
                continue;
            };
            let arg = capture
                .get(1)
                .map(|value| value.as_str().trim())
                .unwrap_or("");
            let line = source[..matched.start()].lines().count() + 1;
            let Some(command) = literal_regex
                .captures(arg)
                .and_then(|literal| literal.get(1))
                .map(|value| value.as_str().to_string())
            else {
                dynamic_calls.push(format!("{}:{}", relative, line));
                continue;
            };

            if !registered.contains(&command) {
                missing_commands.push(format!("{}:{} invokes {}", relative, line, command));
            }
        }
    }

    assert!(
        dynamic_calls.is_empty(),
        "Frontend invoke calls must use literal command names so ACL drift is reviewable: {:?}",
        dynamic_calls,
    );
    assert!(
        missing_commands.is_empty(),
        "Frontend invoke calls drifted from registered Tauri commands: {:?}",
        missing_commands,
    );
}

